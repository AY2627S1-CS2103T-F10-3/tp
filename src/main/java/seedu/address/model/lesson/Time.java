package seedu.address.model.lesson;

/**
 * Represents a time that a lesson can occur at.
 * Uses 24h clock, eg. THIRTEEN refers to 1pm.
 * Ranges from ten to nineteen.
 */
public enum Time {
    TEN,
    ELEVEN,
    TWELVE,
    THIRTEEN,
    FOURTEEN,
    FIFTEEN,
    SIXTEEN,
    SEVENTEEN,
    EIGHTEEN,
    NINETEEN
}
